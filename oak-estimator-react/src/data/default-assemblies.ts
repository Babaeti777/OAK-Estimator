// Helper to get category info
export function getCategoryInfo(categoryId: AssemblyCategory): AssemblyCategoryInfo | undefined {
  return ASSEMBLY_CATEGORIES.find(c => c.id === categoryId)
}

// Helper to get suggested dependencies for a category
export function getSuggestedDependencies(categoryId: AssemblyCategory): AssemblyCategory[] {
  const category = getCategoryInfo(categoryId)
  return category?.suggestedDependencies || []
}

