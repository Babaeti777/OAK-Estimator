// Get count of assemblies by category
export function getAssemblyCountByCategory(): Record<AssemblyCategory, number> {
  const counts = {} as Record<AssemblyCategory, number>
  for (const category of ASSEMBLY_CATEGORIES) {
    counts[category.id] = DEFAULT_ASSEMBLIES.filter(a => a.category === category.id).length
  }
  return counts
}

// Get assemblies filtered by category
export function getAssembliesByCategory(category: AssemblyCategory): Assembly[] {
  return DEFAULT_ASSEMBLIES.filter(a => a.category === category)
}

// Search assemblies by name, description, or tags
export function searchAssemblies(query: string): Assembly[] {
  const lowerQuery = query.toLowerCase()
  return DEFAULT_ASSEMBLIES.filter(a =>
    a.name.toLowerCase().includes(lowerQuery) ||
    a.description?.toLowerCase().includes(lowerQuery) ||
    a.tags?.some(t => t.toLowerCase().includes(lowerQuery))
  )
}
